    exists (
      select 1
      from game_members gm2
      where gm2.game_id = g.id and gm2.user_id = auth.uid()
    ) as is_joined
  from games g
  join sports s on s.id = g.sport_id
  join parks p on p.id = g.park_id
  left join game_members gm on gm.game_id = g.id
  left join profiles pr on pr.id = gm.user_id
  left join parks_ratings prt on prt.park_id = p.id
  where g.id = p_game_id
  group by g.id, s.id, p.id, prt.id;
$$;

create or replace function public.rate_park(
  p_user_id uuid,
  p_park_id uuid,
  p_quality integer,
  p_facilities integer,
  p_activity integer
)
returns void
language plpgsql
security definer
as $$
declare
  existing_review record;
  r record;
begin
  if auth.uid() is null or auth.uid() != p_user_id then
    raise exception 'unauthorized';
  end if;

  if p_quality < 1 or p_quality > 5
    or p_facilities < 1 or p_facilities > 5
    or p_activity < 1 or p_activity > 5 then
    raise exception 'invalid rating values';
  end if;

  select * into existing_review
  from public.park_reviews
  where user_id = p_user_id and park_id = p_park_id;

  if found then
    update public.park_reviews
    set quality = p_quality,
        facilities = p_facilities,
        activity = p_activity
    where user_id = p_user_id and park_id = p_park_id;
  else
    insert into public.park_reviews (
      id, user_id, park_id, quality, facilities, activity
    ) values (
      gen_random_uuid(), p_user_id, p_park_id,
      p_quality, p_facilities, p_activity
    );
  end if;

  select
    avg(quality)::numeric(3,2) as quality_avg,
    avg(facilities)::numeric(3,2) as facilities_avg,
    avg(activity)::numeric(3,2) as activity_avg,
    count(*) as total
  into r
  from public.park_reviews
  where park_id = p_park_id;

  update public.parks_ratings
  set quality_avg = coalesce(r.quality_avg, 0),
      facilities_avg = coalesce(r.facilities_avg, 0),
      activity_avg = coalesce(r.activity_avg, 0),
      overall_avg = (
        coalesce(r.quality_avg, 0)
        + coalesce(r.facilities_avg, 0)
        + coalesce(r.activity_avg, 0)
      ) / 3.0,
      quality_count = r.total,
      facilities_count = r.total,
      activity_count = r.total,
      updated_at = now()
  where park_id = p_park_id;
end;
$$;

create or replace function public.vote_mvp(p_game_id uuid, p_voted_user_id uuid)
returns void
language plpgsql
security definer
as $$
declare
  v_user_id uuid;
  v_voting_open boolean;
  v_is_finished boolean;
  v_voter_exists boolean;
  v_target_exists boolean;
  v_already_voted boolean;
begin
  v_user_id := auth.uid();

  if v_user_id is null then
    raise exception 'Unauthorized';
  end if;
  if v_user_id = p_voted_user_id then
    raise exception 'You cannot vote for yourself';
  end if;

  select mvp_voting_open, is_finished
  into v_voting_open, v_is_finished
  from public.games
  where id = p_game_id;

  if not v_voting_open then
    raise exception 'MVP voting is closed';
  end if;
  if v_is_finished then
    raise exception 'Game already finished';
  end if;

  select exists (
    select 1 from public.game_members
    where game_id = p_game_id and user_id = v_user_id
  ) into v_voter_exists;
  if not v_voter_exists then
    raise exception 'You are not a participant';
  end if;

  select exists (
    select 1 from public.game_members
    where game_id = p_game_id and user_id = p_voted_user_id
  ) into v_target_exists;
  if not v_target_exists then
    raise exception 'Player is not in this game';
  end if;

  select exists (
    select 1 from public.game_mvp_votes
    where game_id = p_game_id and voter_id = v_user_id
  ) into v_already_voted;
  if v_already_voted then
    raise exception 'You already voted';
  end if;

  insert into public.game_mvp_votes (game_id, voter_id, voted_id)
  values (p_game_id, v_user_id, p_voted_user_id);

  update public.profiles
  set perf_points = perf_points + 2
  where id = v_user_id;
end;
$$;

create or replace function public.start_games()
returns void
language plpgsql
security definer
as $$
begin
  update public.games
  set is_in_progress = true
  where is_in_progress = false
    and is_finished = false
    and starts_at <= now();
end;
$$;

create or replace function public.finish_games()
returns void
language plpgsql
security definer
as $$
begin
  update public.games g
  set is_finished = true,
      is_in_progress = false,
      mvp_voting_open = true
  from public.sports s
  where s.id = g.sport_id
    and g.is_in_progress = true
    and g.is_finished = false
    and g.starts_at + make_interval(mins => s.duration_minutes) <= now();
end;
$$;

create or replace function public.open_mvp_voting()
returns void
language plpgsql
security definer
as $$
declare
  v_game record;
begin
  for v_game in
    select g.id, g.sport_id, g.max_players, s.minimum_players_for_rewards
    from public.games g
    join public.sports s on s.id = g.sport_id
    where g.is_in_progress = true
      and g.is_finished = false
      and g.mvp_voting_open = false
      and g.participation_rewards_given = false
      and g.starts_at + make_interval(secs => 20) <= now()
  loop
    if (
      select count(*) from public.game_members gm where gm.game_id = v_game.id
    ) >= v_game.minimum_players_for_rewards then
      update public.profiles
      set rating = rating + 10,
          games_played = games_played + 1,
          perf_points = perf_points + 35
      where id in (
        select user_id from public.game_members where game_id = v_game.id
      );

      update public.user_sport_stats uss
      set rating = uss.rating + 15,
          games_played = uss.games_played + 1,
          perf_points = uss.perf_points + 40
      where uss.sport_id = v_game.sport_id
        and uss.user_id in (
          select user_id from public.game_members where game_id = v_game.id
        );

      update public.game_members
      set rating_change = 15, perf_points_earned = 40
      where game_id = v_game.id;

      update public.games
      set mvp_voting_open = true,
          participation_rewards_given = true
      where id = v_game.id;
    end if;
  end loop;
end;
$$;

create or replace function public.process_finished_games()
returns void
language plpgsql
security definer
as $$
declare
  v_game record;
  v_mvp_user_id uuid;
  v_votes_count int;
begin
  for v_game in
    select g.id, g.sport_id
    from public.games g
    where g.is_finished = true
      and g.is_processed = false
      and g.mvp_voting_open = true
      and g.starts_at + make_interval(mins => 3) <= now()
  loop
    select gmv.voted_id into v_mvp_user_id
    from public.game_mvp_votes gmv
    where gmv.game_id = v_game.id
    group by gmv.voted_id
    order by count(*) desc, random()
    limit 1;

    if v_mvp_user_id is not null then
      select count(*) into v_votes_count
      from public.game_mvp_votes
      where game_id = v_game.id and voted_id = v_mvp_user_id;

      update public.profiles
      set rating = rating + 25 + (v_votes_count * 3),
          perf_points = perf_points + 70 + (v_votes_count * 8),
          mvp_count = mvp_count + 1
      where id = v_mvp_user_id;

      update public.user_sport_stats
      set rating = rating + 35 + (v_votes_count * 5),
          perf_points = perf_points + 80 + (v_votes_count * 10),
          mvp_count = mvp_count + 1
      where user_id = v_mvp_user_id and sport_id = v_game.sport_id;

      update public.game_members
      set was_mvp = true,
          rating_change = rating_change + 35 + (v_votes_count * 5),
          perf_points_earned = perf_points_earned + 80 + (v_votes_count * 10)
      where game_id = v_game.id and user_id = v_mvp_user_id;
    end if;

    update public.games
    set is_in_progress = false,
        mvp_voting_open = false,
        is_processed = true
    where id = v_game.id;
  end loop;
end;
$$;

