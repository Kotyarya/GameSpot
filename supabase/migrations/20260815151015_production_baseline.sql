language sql
security definer
set search_path to 'public'
as $$
  select
    g.id,
    g.starts_at,
    g.duration_minutes,
    g.max_players,
    count(gm.id)::int as joined_players,
    g.is_finished,
    g.is_in_progress,
    g.is_processed,
    g.mvp_voting_open,
    exists (
      select 1
      from game_mvp_votes gmv
      where gmv.game_id = g.id and gmv.voter_id = auth.uid()
