create or replace function public.create_game(
  p_park_id uuid,
  p_sport_id uuid,
  p_starts_at timestamptz
)
returns uuid
language plpgsql
security definer
as $$
declare
  v_user_id uuid;
  v_players_per_team int;
  v_duration_minutes int;
  v_game_id uuid;
  v_sport_exists boolean;
begin
  v_user_id := auth.uid();

  if v_user_id is null then
    raise exception 'Unauthorized';
  end if;

  select exists (
    select 1
    from public.parks_sports
    where park_id = p_park_id and sport_id = p_sport_id
  ) into v_sport_exists;

  if not v_sport_exists then
    raise exception 'Sport not available in this park';
  end if;

  select players_per_team, duration_minutes
  into v_players_per_team, v_duration_minutes
  from public.sports
  where id = p_sport_id;

  if exists (
    select 1
    from public.games g
    where g.park_id = p_park_id
      and g.is_finished = false
      and p_starts_at < g.starts_at + make_interval(mins => g.duration_minutes)
      and p_starts_at + make_interval(mins => v_duration_minutes) > g.starts_at
  ) then
    raise exception 'Another game already exists during this time';
  end if;

  insert into public.games (
    park_id, creator_id, sport_id, starts_at, duration_minutes, max_players
  ) values (
    p_park_id, v_user_id, p_sport_id, p_starts_at,
    v_duration_minutes, v_players_per_team * 2
  ) returning id into v_game_id;

  update public.profiles
  set perf_points = perf_points + 15
  where id = v_user_id;

  update public.user_sport_stats
  set perf_points = perf_points + 10
  where user_id = v_user_id and sport_id = p_sport_id;

  insert into public.game_members (game_id, user_id, team, was_mvp)
  values (v_game_id, v_user_id, 'Team Alpha', false);

  return v_game_id;
end;
$$;

create or replace function public.join_game(p_game_id uuid, p_team public.teams)
returns void
language plpgsql
security definer
as $$
declare
  v_user_id uuid;
  v_max_players int;
  v_team_limit int;
  v_team_count int;
  v_already_joined boolean;
begin
  v_user_id := auth.uid();

  if v_user_id is null then
    raise exception 'Unauthorized';
  end if;

  select max_players into v_max_players
  from public.games
  where id = p_game_id and is_finished = false;

  if v_max_players is null then
    raise exception 'Game not found';
  end if;

  select exists (
    select 1 from public.game_members
    where game_id = p_game_id and user_id = v_user_id
  ) into v_already_joined;

  if v_already_joined then
    raise exception 'User already joined';
  end if;

  v_team_limit := v_max_players / 2;

  select count(*) into v_team_count
  from public.game_members
  where game_id = p_game_id and team = p_team;

  if v_team_count >= v_team_limit then
    raise exception 'Team is full';
  end if;

  insert into public.game_members (game_id, user_id, team)
  values (p_game_id, v_user_id, p_team);
end;
$$;

