    jsonb_build_object('id', s.id, 'name', s.name) as sport,
    jsonb_build_object(
      'id', p.id,
      'name', p.name,
      'latitude', p.latitude,
      'longitude', p.longitude,
      'hasLighting', p.has_lighting,
      'overallAvg', coalesce(prt.overall_avg, 0)
    ) as park,
    coalesce(
      jsonb_agg(
        distinct jsonb_build_object(
          'id', pr.id,
          'username', pr.username,
          'avatarUrl', pr.avatar_url,
          'rating', pr.rating,
          'gamesPlayed', pr.games_played,
          'createdAt', pr.created_at,
          'team', gm.team,
          'mvpVotesCount', (
            select count(*)
            from game_mvp_votes gmv
            where gmv.game_id = g.id and gmv.voted_id = pr.id
          ),
          'isVotedByCurrentUser', exists (
            select 1
            from game_mvp_votes gmv
            where gmv.game_id = g.id
              and gmv.voter_id = auth.uid()
              and gmv.voted_id = pr.id
          ),
          'isTopRated', pr.id = (
            select p1.id
            from profiles p1
            join game_members gm1 on gm1.user_id = p1.id
            where gm1.game_id = g.id
            order by p1.rating desc
            limit 1
          ),
          'isMostActive', pr.id = (
            select p2.id
            from profiles p2
            join game_members gm2 on gm2.user_id = p2.id
            where gm2.game_id = g.id
            order by p2.games_played desc
            limit 1
